/**
 * Concatenates theme CSS into a single critical stylesheet so Next doesn't
 * emit dozens of render-blocking CSS chunk links (major Slow-4G LCP hit).
 *
 * Run: node scripts/build-theme-css.mjs
 * Also runs automatically before `next build` via package.json.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const cssDir = path.join(root, "public", "assets", "css");
const outFile = path.join(cssDir, "theme-critical.css");

const CRITICAL_FILES = [
  "bootstrap.min.css",
  "flaticon.css",
  "style.css",
  "module-css/slider.css",
  "module-css/about.css",
  "module-css/banner.css",
  "module-css/footer.css",
  "responsive.css",
];

function readCss(relPath) {
  const full = path.join(cssDir, relPath);
  let css = fs.readFileSync(full, "utf8");
  // Drop @import rules — we concatenate dependencies explicitly.
  css = css.replace(/@import\s+url\([^)]+\)\s*;?/g, "/* stripped @import */");
  return `/* ===== ${relPath} ===== */\n${css}\n`;
}

// Ensure brand tokens win over any leftover template yellow in concatenated CSS.
const brandPatch = `
/* ===== brand patch (must be last) ===== */
:root {
  --techguru-base: #4c36d5;
  --techguru-base-rgb: 76, 54, 213;
  --techguru-accent-two: #318be2;
  --techguru-brand-gradient: linear-gradient(270deg, var(--techguru-base) 0%, var(--techguru-accent-two) 100%);
}
.thm-btn,
.newsletter-one__contact-form .thm-btn,
.newsletter-two__form .thm-btn {
  background: var(--techguru-brand-gradient) !important;
}
.thm-btn::before,
.thm-btn::after {
  background: var(--techguru-brand-gradient) !important;
}
.thm-btn:hover {
  color: #ffffff !important;
}
`;

const banner = `/* AUTO-GENERATED by scripts/build-theme-css.mjs — do not edit */\n`;
const body = CRITICAL_FILES.map(readCss).join("\n");
fs.writeFileSync(outFile, banner + body + brandPatch, "utf8");

const kb = (fs.statSync(outFile).size / 1024).toFixed(1);
console.log(`Wrote ${outFile} (${kb} KB from ${CRITICAL_FILES.length} files)`);
